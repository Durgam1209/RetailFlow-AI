-- Review and apply manually in the Supabase SQL Editor after validating the app.
-- This migration is intentionally not executed by CI or this repository task.

-- Remove existing policies on these application tables so no permissive legacy
-- policy can continue to widen access after this migration is applied.
DO $$
DECLARE
  policy_row record;
BEGIN
  FOR policy_row IN
    SELECT schemaname, tablename, policyname
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename IN ('sales_log', 'daily_insights')
  LOOP
    EXECUTE format('DROP POLICY %I ON %I.%I',
      policy_row.policyname, policy_row.schemaname, policy_row.tablename);
  END LOOP;
END
$$;

ALTER TABLE public.sales_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_insights ENABLE ROW LEVEL SECURITY;

-- The POS may submit a sale, but public clients cannot read or modify raw rows.
-- The checks mirror the transaction ID and item-list shapes generated by Flutter.
CREATE POLICY "public clients can submit valid sales"
  ON public.sales_log
  FOR INSERT
  TO anon
  WITH CHECK (
    transaction_id ~ '^TXN-[0-9]{8}-[0-9]{6}-[0-9]{4}$'
    AND total_amount >= 0
    AND item_count BETWEEN 0 AND 100
    AND CASE
      WHEN jsonb_typeof(items) = 'array' THEN jsonb_array_length(items) = item_count
      ELSE false
    END
    AND jsonb_typeof(weather) = 'object'
  );

-- Daily insights are intentionally public app content. No customer data belongs
-- in this table; the app's anonymous key needs read access to the latest advice.
CREATE POLICY "Anyone can read daily insights"
  ON public.daily_insights
  FOR SELECT
  TO anon
  USING (true);

REVOKE ALL ON TABLE public.sales_log FROM PUBLIC, anon, authenticated;
GRANT INSERT ON TABLE public.sales_log TO anon;
GRANT ALL ON TABLE public.sales_log TO service_role;

REVOKE ALL ON TABLE public.daily_insights FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.daily_insights TO anon;
GRANT INSERT ON TABLE public.daily_insights TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.daily_insights_id_seq TO service_role;

-- This view contains only per-day totals, not raw transaction rows. Keep its
-- owner-rights behavior so the app can query aggregates after sales_log SELECT
-- is revoked, while granting the view itself only to app roles.
ALTER VIEW public.daily_sales_summary SET (security_invoker = false);
REVOKE ALL ON public.daily_sales_summary FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.daily_sales_summary TO anon, authenticated;
